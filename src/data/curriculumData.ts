// Helper: retorna o ano a partir do identificador da turma (ex: '7B' → '7', '9F' → '9')
export function getAnoFromTurma(turma: string): string {
  const match = turma.match(/^(\d+)/);
  return match ? match[1] : '';
}

// Helper: retorna os dados curriculares para uma turma e bimestre específicos
export function getCurriculumData(turma: string, bimestre: string): BimestreData | null {
  const ano = getAnoFromTurma(turma);
  if (!ano || !curriculumData[ano]) return null;
  const bimestreKey = bimestre.replace(/[ºo°].*/, '').trim();
  return curriculumData[ano]?.bimestres?.[bimestreKey] || null;
}

